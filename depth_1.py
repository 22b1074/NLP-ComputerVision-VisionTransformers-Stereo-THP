def load_pfm(file_path):
    """
    Load a PFM (Portable Float Map) file and return a numpy array.
    """
    with open(file_path, 'rb') as f:
        header = f.readline().rstrip().decode('utf-8')
        color = header == 'PF'

        # Read width and height
        dim_line = f.readline().decode('utf-8')
        while dim_line.startswith('#'):  # skip comments
            dim_line = f.readline().decode('utf-8')
        width, height = map(int, dim_line.strip().split())

        # Read scale (negative value means little-endian)
        scale = float(f.readline().decode('utf-8').strip())
        endian = '<' if scale < 0 else '>'
        scale = abs(scale)

        # Read pixel data
        data = np.fromfile(f, endian + 'f')
        shape = (height, width, 3) if color else (height, width)
        data = np.reshape(data, shape)
        data = np.flipud(data)  # PFM has origin at bottom-left
        return data

import numpy as np
import time

def compute_d1_error(pred_disp, gt_disp, mask=None):
    """
    Compute D1-all error.

    Args:
        pred_disp: predicted disparity (H x W)
        gt_disp: ground truth disparity (H x W)
        mask: optional boolean mask to consider valid pixels (default: finite & >0)
    Returns:
        d1_all (%), d1_noc (%)
    """
    if mask is None:
        mask = np.isfinite(gt_disp) & (gt_disp > 0)

    # Absolute error
    error = np.abs(pred_disp - gt_disp)

    # D1 condition: error > 3 px OR > 5% of true disparity
    d1_mask = mask & ((error > 3) & (error / gt_disp > 0.05))
    d1_all = 100.0 * np.sum(d1_mask) / np.sum(mask)

    # Non-occluded mask (assuming gt_disp has occlusion info, if not, use mask)
    d1_noc = d1_all  # If no occlusion info, treat same as all

    return d1_all, d1_noc

