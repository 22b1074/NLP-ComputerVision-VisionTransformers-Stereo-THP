def performance_metrics(depth_map, ground_truth):
  print(f"Depth map range: {depth_map.min()} to {depth_map.max()}")
  print(f"Ground truth range: {ground_truth.min()} to {ground_truth.max()}")
  # Normalize both depth map and ground truth to [0, 1]
  depth_map_norm = normalize_map(depth_map)
  ground_truth_norm = normalize_map(ground_truth)

  # Print normalized ranges
  print(f"Normalized Depth map range: {depth_map_norm.min()} to {depth_map_norm.max()}")
  print(f"Normalized Ground truth range: {ground_truth_norm.min()} to {ground_truth_norm.max()}")

  mse = np.mean((depth_map_norm - ground_truth_norm) ** 2)
  ssim_index = ssim(depth_map_norm, ground_truth_norm, data_range=1.0)
  return mse, ssim_index

