def load_calibration(calib_file):
  with open(calib_file, 'r') as f:
    lines = f.readlines()

  cam0 = cam1 = None
  baseline = None

  for line in lines:
        if line.startswith('cam0='):
            # Extract and reshape cam0
            cam0_data = line.split('=')[1].strip().strip('[]').replace(';', '').split()
            cam0 = np.array([float(x) for x in cam0_data]).reshape(3, 3)
        elif line.startswith('cam1='):
            # Extract and reshape cam1
            cam1_data = line.split('=')[1].strip().strip('[]').replace(';', '').split()
            cam1 = np.array([float(x) for x in cam1_data]).reshape(3, 3)
        elif line.startswith('baseline='):
            # Extract baseline and convert to float
            baseline_value = line.split('=')[1].strip()  # Get the right side of the '='
            baseline = float(baseline_value)

  return cam0, cam1, baseline

