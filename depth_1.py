def process_stereo_images(left_image_path, right_image_path, calib_file, model, ground_truth_path=None):
    cam0, cam1, baseline = load_calibration(calib_file)
    focal_length = cam0[0, 0]

    left_image = cv2.imread(left_image_path, cv2.IMREAD_COLOR)
    right_image = cv2.imread(right_image_path, cv2.IMREAD_COLOR)
    # Measure runtime
    start_time = time.time()
    disparity = compute_disparity(left_image, right_image, model)
    runtime = time.time() - start_time

    # Convert to depth
    depth_map = disparity_to_depth(disparity, baseline, focal_length)
    depth_map_normalized = cv2.normalize(depth_map, None, 0, 255, cv2.NORM_MINMAX).astype(np.uint8)
    # Apply color map to depth map
    depth_color_normalized = cv2.applyColorMap(depth_map_normalized, cv2.COLORMAP_PLASMA)



    if ground_truth_path and os.path.exists(ground_truth_path):
        gt_disp = load_pfm(ground_truth_path)

        # Mask invalid pixels
        mask = np.isfinite(gt_disp) & (gt_disp > 0)
        gt_valid = gt_disp[mask]
        pred_valid = disparity[mask]  # Use disparity for D1 metric

        # Normalize safely for SSIM
        gt_norm = (gt_valid - np.min(gt_valid)) / (np.ptp(gt_valid) + 1e-8)
        pred_norm = (pred_valid - np.min(pred_valid)) / (np.ptp(pred_valid) + 1e-8)

        # Metrics
        mse = np.mean((pred_valid - gt_valid)**2)
        ssim_index = ssim(gt_norm, pred_norm, data_range=1.0)
        d1_all, d1_noc = compute_d1_error(disparity, gt_disp, mask=mask)

        print(f"D1-all: {d1_all:.2f}%, D1-noc: {d1_noc:.2f}%")
        print(f"MSE: {mse:.4f}, SSIM: {ssim_index:.4f}, Runtime: {runtime:.3f}s")

    # Show images and maps
    print('Left Image:')
    cv2_imshow(left_image)
    print('Right Image:')
    cv2_imshow(right_image)
    print('Disparity Map:')
    disp_vis = cv2.applyColorMap(cv2.convertScaleAbs(disparity, alpha=255/np.max(disparity)), cv2.COLORMAP_JET)
    cv2_imshow(disp_vis)
    print('Depth Map Normalized:')
    cv2_imshow(depth_color_normalized)

